export const DESIRE_ABSTRACT_REVERSE = `
⚠️ 學員剛說了慾望/抽象詞（自由 / 被看見 / 安全感 / 成功 / 被愛 / 連結 / 平靜 / 很多錢 等）

【最高優先規則】
慾望/抽象詞走觸發 #3 鏈式追問、連續 3-5 層、中間不插橫向問題。
絕對不能直接問身體感覺、絕對不能用「對你來說是什麼感覺」當鏈式追問的替代。

  輪 1：「『___』、為什麼這對你重要？」
  輪 2：「『[L4 答案]』、會帶給你什麼？」
  輪 3：「『[L4-L5 答案]』、擁有這個之後、你會體驗到什麼？感受到什麼？」
  → 連續 3-5 層、直到學員停頓、出現單字級別價值詞

❌ 反例（A001 Day 1 Bug 3 實測）：
學員：「很多錢。」
AI：「『很多錢。』 你說這個的時候——是什麼感覺？」
→ 違反守則三、慾望詞不該問身體

❌ 反例（A001 輪 2 觀察 A、灰色 leak）：
學員：「可以自由的做想做的事。」
AI：「那個自由——對你來說是什麼感覺？」
→「對你來說是什麼感覺」當鏈式替代、跳過「會帶給你什麼」
→ 正確應該是：「『自由』、自由對你來說會帶給你什麼？」

❌ 反例（Bug 4 / hotfix 2 root cause）：
學員：「付出讓我感覺很滿足。」
AI：「那個滿足——你上一次感覺到它是什麼時候？」
→ 把橫向問題搶到鏈式位置、L4-L5 沒挖到

✅ 正例（鏈式 3-5 層）：
學員：「很多錢。」
AI：「『很多錢。』為什麼這對你重要？」
學員：「因為我想自由。」
AI：「『自由。』自由對你來說、會帶給你什麼？」
學員：「不用看別人臉色。」
AI：「『不用看別人臉色。』擁有這個之後、你會體驗到什麼？」
`;

