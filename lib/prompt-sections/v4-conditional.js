export function getV4StaticConditional(week, day) {
  const parts = [];
  if (week === 2 && day === 3) parts.push(ROLE_ASSIGNMENT_FOUR_STEPS);
  if (week === 2 && day >= 4) {
    parts.push(`【提醒】Week 2 Day 3 賦予新角色已完成、今天 2C Step3 反例提問才有效。
若 Damon Note【賦予新角色狀態】顯示未完成、不做 Step3、回 Day 3 補上。`);
  }
  if (week === 3 && (day === 3 || day === 4)) parts.push(FIVE_CORE_CATEGORIES);
  if (week === 3 && day === 4) parts.push(SCOPE_OVERLAP_THREE_LAYERS);
  if (week === 3 && day === 5) parts.push(COUNTEREXAMPLE_FOUR_STEPS);
  return parts.length ? '\n\n' + parts.join('\n\n') : '';
}

export function getV4DynamicConditional(week, day, latestUserMessage) {
  const parts = [];
  if (week === 2 && day <= 2 && hasResentmentPattern(latestUserMessage)) {
    parts.push(RESENTMENT_FOUR_STEPS);
  }
  return parts.length ? '\n\n' + parts.join('\n\n') : '';
}

function hasResentmentPattern(msg) {
  if (!msg) return false;
  return /都是.{0,3}的錯|如果不是.{0,5}(?:他|她|他們|爸|媽|父|母)|氣不過|不甘心|憑什麼|怪.{0,3}(?:他|她|他們)|(?:他|她|他們)害我|為什麼.{0,8}(?:他|她).{0,3}要/.test(msg);
}
